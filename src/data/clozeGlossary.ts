/**
 * 取得填空題正確答案（blankWord）的純假名讀音
 */
export function getBlankWordKana(example: ExampleSentence): string {
  const { kana, cloze } = example;
  const start = cloze.kanaBefore.length;
  const end = kana.length - cloze.kanaAfter.length;
  if (end > start && kana.startsWith(cloze.kanaBefore) && kana.endsWith(cloze.kanaAfter)) {
    return kana.slice(start, end);
  }
  return cloze.blankWord;
}

/**
 * 解析單一干擾選項的假名與簡短中文說明
 */
export function resolveClozeOptionInfo(
  surface: string,
  vocabByKanji: Record<string, VocabEntry>
): ClozeOptionInfo {
  const directVocab = vocabByKanji[surface];
  if (directVocab) {
    return {
      surface,
      kana: directVocab.kana,
      meaning: directVocab.meaning,
    };
  }

  const glossary = DISTRACTOR_GLOSSARY[surface];
  if (glossary) {
    return {
      surface,
      kana: glossary.kana,
      meaning: glossary.meaning,
    };
  }

  return {
    surface,
    kana: surface,
    meaning: '干擾選項',
  };
}
